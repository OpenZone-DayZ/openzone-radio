        // що й індекс: EnableBroadcast -- рушійний стан, і SetSynchDirty про
        // нього нічого не знає. Без цього числа squelch чув би лише той, хто
        // натиснув, бо звук грає КЛІЄНТ, а рішення приймає сервер.
        //
        // Реєструється в конструкторі МОДОВАНОГО TransmitterBase, тобто в
        // усіх передавачів гри -- і в ручної рації, і в плати КПК
        // (OZ_Module_Radio extends TransmitterBase), і в ванільної
