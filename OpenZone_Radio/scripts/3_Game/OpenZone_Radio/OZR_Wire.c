// Що їде по проводу між сервером і клієнтом рації -- з 2026-09-20 конвертами
// ядра, а не власними RPC.
//
// ЕФІР їде додатками до пакета синхронізації ядра (OZ_Sync): сітка, гучності
// й рівень діагностики -- одним об'єктом під ключем OZR_Const.SYNC_ETHER,
// профілі -- ПО ОДНОМУ під ключами SYNC_RADIO + номер, а їх число -- під
// SYNC_RADIOS. Не одним об'єктом, і це зміряно (2026-09-20): нарізка OZ_Sync
// на частини знімає межу рушійного RPC (~1024 байти), але НЕ межу
// JsonFileLoader, який мовчки ріже будь-яке СТРОКОВЕ ЗНАЧЕННЯ JSON на 1023
// байтах (див. OZ_Const.NEWS_BODY_MAX). Додаток -- саме таке значення: ефір з
// одинадцятьма профілями важив ~1300 байтів, приїздив обрізаним, не
// розбирався, і клієнт лишався на ванільних 87.8 -- мовчки, бо ретейл-клієнт
// не пише лога. Профіль окремо -- це ~90 байтів, і жоден додаток не росте з
// числом профілів.
//
// НАСТРОЙКА й ГАШЕТКА їдуть парою служби (OZ_Rpc.ServiceRequest) двома
// маленькими JSON. Корінь кожного створює скрипт (new), а не серіалізатор,
// тож поля з умовчаннями безпечні (шапка OZ_ConfigBase); вкладені профілі
// ефіру клієнт переписує в OZR_ClientGrid одразу при розборі й довше не тримає.

class OZR_EtherWire
{
    // Сітка. Нулі означають «ефіру немає»: сервер не описує ванільну вісімку
    // як сітку (див. OZR_EtherServer.Fill), а клієнт нулі вже вміє читати --
    // підпис падає на ванільний, клавіатура не відкривається.
    // BaseMHz/StepMHz, а не Base/Step: `Step` у ванілі -- ім'я класу, і поле з
    // таким ім'ям не компілюється («Variable name 'Step' already used as type
    // name», зміряно 2026-09-20).
    float BaseMHz = 0;
    float StepMHz = 0;
    int   Count   = 0;

    // Гучності й правила гашетки -- завжди, навіть без сітки.
    float Squelch = 1.0;
    bool  Mirror  = true;
    int   Range   = OZR_Const.SQUELCH_RANGE_DEFAULT;
    bool  Cargo   = true;

    // ЖИВИЙ рівень діагностики сервера: клієнт мусить мовчати чи говорити
    // разом із ним (див. OZR_Log). DebugLog, а не Debug -- `Debug` у ванілі
    // теж ім'я типу (зміряно 2026-09-20, той самий відказ, що й на Step).
    bool  DebugLog = false;

    // Профілів тут НЕМАЄ -- вони їдуть окремими додатками, див. шапку.
}

