    // тридцять», і 25 тут чесніше за 10.
    static int SquelchRung(int want)
    {
        if (want <= 7)
            return 5;
        if (want <= 12)
            return 10;
        if (want <= 17)
            return 15;
        if (want <= 22)
            return 20;

        return 25;
    }

